"""
Base Strategy Interface
=======================
Defines the standard contract for all trading strategies in the platform.
Supports plug-and-play strategy development, deterministic shared indicator
helpers, and independent ablation testing.
"""

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

import pandas as pd

from app.models import (
    Candle,
    EvidenceItem,
    MultiAttributeRegime,
    SignalDirection,
)


def safe_float(row: Any, key: str, default: Optional[float] = None) -> Optional[float]:
    """Extracts a finite float value from a Series/mapping row cleanly."""
    if row is None:
        return default
    val = row.get(key) if hasattr(row, "get") else None
    if val is None or pd.isna(val):
        return default
    return float(val)


def extract_atr(ctx: "StrategyContext") -> float:
    """
    Returns valid ATR > 0 from enriched indicators or direct candle true range.
    Never invents arbitrary hardcoded pip constants across multi-scale assets.
    """
    if not ctx.df_enriched.empty:
        atr_val = safe_float(ctx.df_enriched.iloc[-1], "atr", default=None)
        if atr_val is not None and atr_val > 0.0:
            return atr_val

    candles = ctx.candles
    if len(candles) >= 2:
        recent = candles[-min(15, len(candles)) :]
        trs = []
        for idx in range(1, len(recent)):
            curr = recent[idx]
            prev_c = recent[idx - 1].close
            tr = max(
                curr.high - curr.low,
                abs(curr.high - prev_c),
                abs(curr.low - prev_c),
            )
            trs.append(tr)
        if trs:
            mean_tr = sum(trs) / len(trs)
            if mean_tr > 0.0:
                return float(mean_tr)
    return 0.0


@dataclass
class StrategyContext:
    """Consolidated market data & features passed into strategies."""

    symbol: str
    candles: List[Candle]
    df_enriched: pd.DataFrame
    regime: MultiAttributeRegime
    extra_timeframe_candles: Dict[str, List[Candle]] = field(default_factory=dict)


@dataclass
class StrategySignalResult:
    """Output generated by a single strategy."""

    strategy_name: str
    direction: SignalDirection
    confidence: float
    evidence_items: List[EvidenceItem] = field(default_factory=list)
    suggested_expiry_seconds: int = 300
    metadata: Dict[str, Any] = field(default_factory=dict)


class BaseStrategy(ABC):
    """Abstract Base Class for all signal-generating strategies."""

    name: str = "BaseStrategy"
    version: str = "1.0.0"
    description: str = ""
    target_regimes: List[str] = []
    prohibited_regimes: List[str] = []
    min_adx: float = 0.0

    @abstractmethod
    def evaluate(self, ctx: StrategyContext) -> Optional[StrategySignalResult]:
        """
        Evaluates the current market state and returns a StrategySignalResult if a setup is detected.
        Must be strictly causal (only past data up to the current candle).
        """
        pass

    def is_regime_compatible(self, regime: MultiAttributeRegime) -> bool:
        """Checks if current market regime permits this strategy to run."""
        if self.min_adx > 0.0 and regime.adx_value < self.min_adx:
            return False

        if self.prohibited_regimes:
            if regime.structure.value in self.prohibited_regimes:
                return False
            if regime.trend.value in self.prohibited_regimes:
                return False
            if regime.volatility.value in self.prohibited_regimes:
                return False

        if self.target_regimes:
            return (
                regime.structure.value in self.target_regimes
                or regime.trend.value in self.target_regimes
                or regime.volatility.value in self.target_regimes
            )

        return True
